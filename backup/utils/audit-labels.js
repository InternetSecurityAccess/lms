function getActionLabel(code) {
  return LABELS[code] || code;
}

function buildActionGroups(actions) {
  const GROUP_DEFS = [
    { title: 'Аутентификация и безопасность',
      codes: ['auth.login', 'auth.brute_force', 'rate_limit.block'] },
    { title: 'Служебные операции',
      codes: ['audit.cleanup', 'slow_log.cleanup'] },
    { title: 'Пользователи: заявки',
      codes: ['student.reject', 'student.approve', 'teacher.reject'] },
    { title: 'Пользователи: доступ',
      codes: ['student.archive', 'student.unarchive', 'student.delete',
              'student.finish', 'student.activate',
              'teacher.activate', 'teacher.archive', 'teacher.delete',
              'session.logout_all', 'session.delete'] },
    { title: 'Пользователи: логины и пароли',
      codes: ['student.change_login', 'student.reset_password',
              'teacher.change_login', 'teacher.reset_password'] },
    { title: 'Пользователи: правка данных',
      codes: ['student.create', 'student.change_name', 'student.change_group',
              'teacher.create', 'teacher.change_name', 'teacher.update_max'] },
    { title: 'Группы',
      codes: ['group.create', 'group.rename', 'group.archive',
              'group.unarchive', 'group.delete', 'group.delete_blocked'] },
    { title: 'Предметы',
      codes: ['subject.create', 'subject.update', 'subject.archive',
              'subject.unarchive', 'subject.delete', 'subject.attach_group',
              'subject.detach_group', 'subject.groups_update',
              'subject.change_teacher',
              // ─── Завершение предмета для группы ───
              'subject_groups.finish', 'subject_groups.restore',
              'subject_groups.bulk_accept', 'subject_groups.bulk_reject'] },
    { title: 'Темы',
      codes: ['topic.create', 'topic.update', 'topic.delete', 'topic.import'] },
    { title: 'Задания',
      codes: ['assignment.create', 'assignment.update', 'assignment.archive',
              'assignment.unarchive', 'assignment.delete',
              'assignment.archive_on_delete'] },
    { title: 'Работы студентов',
      codes: ['submission.status', 'submission.archive',
              'submission.unarchive', 'submission.delete',
              'submission.reject_ai'] },
    { title: 'Объявления',
      codes: ['announcement.create', 'announcement.update',
              'announcement.delete', 'announcement.pin', 'announcement.unpin'] },
    { title: 'Массовые операции',
      codes: ['teacher.bulk_delete', 'teacher.bulk_archive', 'teacher.bulk_unarchive',
              'teacher.bulk_finish', 'teacher.bulk_activate',
              'student.bulk_delete', 'student.bulk_archive', 'student.bulk_unarchive',
              'student.bulk_finish', 'student.bulk_activate',
              'group.bulk_delete', 'group.bulk_archive', 'group.bulk_unarchive',
              'group.bulk_finish', 'group.bulk_activate',
              'subject.bulk_delete', 'subject.bulk_archive', 'subject.bulk_unarchive',
              'subject.bulk_finish', 'subject.bulk_activate',
              'topic.bulk_delete',
              'submission.bulk_delete', 'submission.bulk_archive', 'submission.bulk_unarchive',
              'announcement.bulk_delete', 'group_announcement.bulk_delete',
              'student.bulk_approve', 'student.bulk_reject'] },
    { title: 'Система',
      codes: ['settings.update',
              'import.teachers', 'import.students', 'import.groups',
              'export.teachers', 'export.students', 'export.groups',
              'demo.seed', 'demo.delete'] },
  ];
  const set = new Set(actions);
  const placed = new Set();
  const result = [];
  for (const def of GROUP_DEFS) {
    const items = def.codes
      .filter((c) => set.has(c))
      .map((c) => ({ code: c, label: getActionLabel(c) }));
    if (items.length === 0) continue;
    items.forEach((i) => placed.add(i.code));
    result.push({ title: def.title, actions: items });
  }
  const others = actions
    .filter((a) => !placed.has(a))
    .map((c) => ({ code: c, label: getActionLabel(c) }));
  if (others.length > 0) result.push({ title: 'Прочее', actions: others });
  return result;
}

module.exports = { LABELS, getActionLabel, buildActionGroups };