const DYNAMIC = {
  '/help': () => null,
};

function getHelp(path, locals) {
  const s = STATIC[path];
  if (s) return { type: s.type, html: s.text };
  const d = DYNAMIC[path];
  if (typeof d === 'function') {
    const r = d(locals);
    if (!r) return null;
    if (typeof r === 'string') return { type: 'blue', html: r };
    return r;
  }
  return null;
}

module.exports = { getHelp, STATIC, DYNAMIC };